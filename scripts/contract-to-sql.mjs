#!/usr/bin/env node
// Writes deploy/create/generated/96_contract.sql, which loads the application's contract, with the
// framework fragments it includes merged in, into ROAD_CONTRACT, so GET /contract/ serves exactly
// the document that was validated (spec-patch-16 section 3.1). It validates first and writes nothing
// for an invalid contract.
//
//   node scripts/contract-to-sql.mjs [contract/<app>.gsc.json]
//   bin/run-sql.sh --env dev --script deploy/create/generated/96_contract.sql
//
// The contract defaults to contract/<APP_NAME>.gsc.json, APP_NAME from road.config.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveContract } from './lib/contract-merge.mjs';
import { checkContract, loadSchema } from './validate-gsc-contract.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const appName = /^APP_NAME=(.+)$/m.exec(fs.readFileSync(path.join(root, 'road.config'), 'utf8'))?.[1].trim();
const file = path.resolve(process.argv[2] ?? path.join(root, 'contract', `${appName}.gsc.json`));
const { contract, includes } = resolveContract(file);
const problems = checkContract(await loadSchema(), contract);
if (problems.length) {
  for (const p of problems) console.error(`[FAIL] ${p}`);
  process.exit(1);
}
const version = contract.envelope.contract_version;
const compact = JSON.stringify(contract);
if (compact.includes('~]')) throw new Error('contract contains the quote terminator ~]');
const chunks = compact.match(/[\s\S]{1,3000}/g);
const rel = path.relative(root, file);
const sql = `whenever oserror exit failure rollback
whenever sqlerror exit sql.sqlcode rollback
-- GENERATED by scripts/contract-to-sql.mjs from ${rel}${includes.length ? ` and fragments ${includes.join(', ')}` : ''}. Do not edit.
-- INTENT:
-- Purpose: Load ${rel}, version ${version}, into ROAD_CONTRACT for GET /contract/.
-- Approach: Generated by scripts/contract-to-sql.mjs. The document is appended in chunks and merged
--   into the one row.
-- Reason: The contract is discoverable at request time (definition 5.5); one source for the version
--   on every response (spec-patch-16 section 6.3).
-- Expected objects: one ROAD_CONTRACT row.
-- Risk: Low.
-- Prior history checked: generated; see the generator.
-- END INTENT
declare
  l_doc clob;
begin
  dbms_lob.createtemporary(l_doc, true);
${chunks.map((c) => `  dbms_lob.append(l_doc, to_clob(q'~${c}~'));`).join('\n')}
  merge into road_contract c
  using (select 1 contract_id from dual) s on (c.contract_id = s.contract_id)
  when matched then update set contract_version = '${version}', document = l_doc, loaded_at = systimestamp
  when not matched then insert (contract_id, contract_version, document) values (1, '${version}', l_doc);
  commit;
end;
/
select 'CONTRACT ' || contract_version || ' ' || dbms_lob.getlength(document) || ' chars' from road_contract;
`;
const out = path.join(root, 'deploy', 'create', 'generated', '96_contract.sql');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, sql);
console.log(`[INFO] Wrote ${path.relative(root, out)}: contract ${version}, ${compact.length} chars`);
