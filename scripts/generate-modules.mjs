#!/usr/bin/env node
// Generates an application's ORDS module files, api/modules/<name>/module.create.sql and
// module.drop.sql, from the route list in api/routes.mjs (spec-patch-16 section 3.4). Every handler
// has the same thin shape (definition 6.3): establish the session or answer 401, check
// Accept-Version, make one package call, send what it returns. Governed actions answer 200 whatever
// they decide; wrong calls and failures go through road_surface_api.fail and error_api. No business
// rule can live in a handler.
//
//   node scripts/generate-modules.mjs          write the module files
//   node scripts/generate-modules.mjs --check  fail if any file is stale
//
// api/routes.mjs default-exports an array of modules:
//   { name, base, comment, routes: [ { pattern, method, id, kind, call, idempotency, headers } ] }
//     name         folder under api/modules/, and the module's suffix after the alias (road.config
//                  API_BASE_PATH), as in hello_api.todos
//     base         the module's base path, such as /api/v1/todos/
//     pattern      the URI template within it, such as :id/revisions/
//     id           the contract id the route serves; test/contract/check-contract-coverage.mjs
//                  compares the deployed routes with the contract
//     kind         'action' (the call returns JSON, sent as it is) or 'view' (it returns a CLOB)
//     call         the PL/SQL call. Binds are the path parameters, the query parameters, :body_text,
//                  and the headers below. {n:id} is id as a number, null when it is not one.
//     idempotency  true when the route reads the Idempotency-Key header, bound as :idempotency_key
//     headers      further request headers as [header, bind] pairs
// Privileges (privileges.create.sql) stay hand-written: a module's URL gate is a decision.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const alias = /^API_BASE_PATH=(.+)$/m.exec(fs.readFileSync(path.join(root, 'road.config'), 'utf8'))?.[1].trim();
if (!alias) throw new Error('road.config has no API_BASE_PATH');
const modules = (await import(pathToFileURL(path.join(root, 'api', 'routes.mjs')).href)).default;

const expand = (call) => call.replace(/\{n:([a-z_]+)\}/g, (_, b) => `to_number(:${b} default null on conversion error)`);
const parameter = (mod, pattern, method, header, bind) =>
  `  ords.define_parameter(p_module_name => '${mod}', p_pattern => '${pattern}', p_method => '${method}',
    p_name => '${header}', p_bind_variable_name => '${bind}', p_source_type => 'HEADER',
    p_param_type => 'STRING', p_access_method => 'IN');
`;

function createScript(m) {
  const mod = `${alias}.${m.name}`;
  let out = `whenever oserror exit failure rollback
whenever sqlerror exit sql.sqlcode rollback

-- GENERATED by scripts/generate-modules.mjs from api/routes.mjs. Edit the route list, not this file.
--
-- ${m.comment ?? mod} (${m.base}). Thin handlers: establish the session or answer 401, check
-- Accept-Version, make one package call, send what it returns. Governed actions answer 200 whatever they decide; wrong calls and failures go through
-- road_surface_api.fail and error_api. No business rule lives here (definition 6.3).
-- "query" not "q": ORDS reserves q globally for its AutoREST filter syntax.

begin
  ords.delete_module(p_module_name => '${mod}');
exception
  when others then
    null;
end;
/

begin
  ords.define_module(
    p_module_name    => '${mod}',
    p_base_path      => '${m.base}',
    p_items_per_page => 0,
    p_status         => 'PUBLISHED',
    p_comments       => '${(m.comment ?? mod).replace(/'/g, "''")}');
`;
  const templates = new Set();
  for (const r of m.routes) {
    if (!templates.has(r.pattern)) {
      templates.add(r.pattern);
      out += `\n  ords.define_template(p_module_name => '${mod}', p_pattern => '${r.pattern}');\n`;
    }
    const call = expand(r.call);
    const body = r.kind === 'action' ? `l_out := json_serialize(${call} returning clob);` : `l_out := ${call};`;
    out += `
  -- ${r.method} ${m.base}${r.pattern === '/' ? '' : r.pattern}  (${r.id})
  ords.define_handler(
    p_module_name => '${mod}',
    p_pattern     => '${r.pattern}',
    p_method      => '${r.method}',
    p_source_type => ords.source_type_plsql,
    p_source      => q'~
      declare
        l_out clob;
      begin
        if not road_ctx_pkg.begin_request(:current_user) then
          road_surface_api.unauthorized;
          return;
        end if;
        if not road_surface_api.version_ok(:accept_version) then
          return;
        end if;
        ${body}
        road_surface_api.respond(200, l_out);
      exception
        when others then
          road_surface_api.fail(sqlcode, sqlerrm, dbms_utility.format_error_backtrace, '${r.id}');
      end;~');
${parameter(mod, r.pattern, r.method, 'Accept-Version', 'accept_version')}`;
    if (r.idempotency) out += parameter(mod, r.pattern, r.method, 'Idempotency-Key', 'idempotency_key');
    for (const [header, bind] of r.headers ?? []) out += parameter(mod, r.pattern, r.method, header, bind);
  }
  return out + '\n  commit;\nend;\n/\n';
}

const dropScript = (m) => `whenever oserror exit failure rollback
whenever sqlerror exit sql.sqlcode rollback

-- GENERATED by scripts/generate-modules.mjs.
begin
  ords.delete_module(p_module_name => '${alias}.${m.name}');
  commit;
exception
  when others then
    null;
end;
/
`;

let stale = 0;
for (const m of modules) {
  const dir = path.join(root, 'api', 'modules', m.name);
  for (const [file, text] of [['module.create.sql', createScript(m)], ['module.drop.sql', dropScript(m)]]) {
    const target = path.join(dir, file);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) {
        console.error(`[FAIL] ${path.relative(root, target)} is stale: run node scripts/generate-modules.mjs`);
        stale += 1;
      }
    } else {
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(target, text);
    }
  }
  if (!check) console.log(`[INFO] ${m.name}: ${m.routes.length} handler(s)`);
}
if (check) {
  if (stale) process.exit(1);
  console.log(`[PASS] generated modules are current (${modules.length} modules)`);
}
